const phrases = Object.entries(readerMessages).sort((a, b) => b[0].length - a[0].length);

export function readerText(message: string): string {
  if (useI18n.getState().lang !== 'en') return message;
  if (readerMessages[message]) return readerMessages[message];
  // Electron adds an English IPC prefix to native errors; preserve it and any path.
  return phrases.reduce((text, [zh, en]) => text.split(zh).join(en), message);
}
export function useReaderT() {
  useI18n(s => s.lang);
  return readerText;
}
